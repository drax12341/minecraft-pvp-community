package community.pvp.arena;

import java.util.*;

import org.bukkit.*;
import org.bukkit.scheduler.BukkitRunnable;

/**
 * Original, deterministic terrain; no downloaded builds or survival-world edits.
 */
final class BattleMaps {
    static final int FIRST = 6, LAST = 23;
    static final String[] THEMES = {"Meadow", "Dunes", "Jungle", "Alpine", "Cherry", "Badlands"};
    static final Material[] ICONS = {Material.GRASS_BLOCK, Material.SAND, Material.JUNGLE_SAPLING,
            Material.SNOW_BLOCK, Material.CHERRY_SAPLING, Material.RED_SAND};

    record MapInfo(int id, int theme, int size) {
        int width() {
            return ImportedBuilds.is(id) ? ImportedBuilds.build(id).width() : new int[]{50, 150, 250}[size];
        }

        int length() {
            return ImportedBuilds.is(id) ? ImportedBuilds.build(id).length() : new int[]{50, 250, 350}[size];
        }

        int ceiling() {
            return ImportedBuilds.is(id) ? Math.min(310, Math.max(180, ImportedBuilds.build(id).baseY() + ImportedBuilds.build(id).height() + 48)) : new int[]{110, 180, 280}[size];
        }

        int cx() {
            return ImportedBuilds.is(id) ? 20000 + (id - ImportedBuilds.FIRST) * 1024 : 2048 + (id - FIRST) * 512;
        }

        String name() {
            if (ImportedBuilds.is(id)) return ImportedBuilds.NAMES[theme];
            return THEMES[theme] + " / " + new String[]{"Compact", "Standard", "Sky"}[size];
        }

        boolean supports(String kit) {
            return size == 0 || !Set.of("sword", "axe", "uhc", "boxing", "bow").contains(kit);
        }

        boolean inside(Location l, World world, int margin) {
            return l.getWorld().equals(world) && l.getX() >= cx() - width() / 2 + margin
                    && l.getX() < cx() - width() / 2 + width() - margin && l.getZ() >= 1024 - length() / 2 + margin
                    && l.getZ() < 1024 - length() / 2 + length() - margin && l.getY() >= 50 && l.getY() < ceiling() - margin;
        }
    }

    static final List<MapInfo> MAPS = java.util.stream.IntStream.rangeClosed(FIRST, LAST).mapToObj(id -> new MapInfo(id, (id - FIRST) / 3, (id - FIRST) % 3)).toList();

    static MapInfo get(int id) {
        return ImportedBuilds.is(id) ? ImportedBuilds.get(id) : id < FIRST || id > LAST ? null : MAPS.get(id - FIRST);
    }

    static MapInfo at(int x, int z) {
        return x >= 19488 ? ImportedBuilds.at(x, z) : legacyAt(x, z);
    }

    static MapInfo legacyAt(int x, int z) {
        int n = Math.floorDiv(x - 1792, 512);
        int id = FIRST + n;
        MapInfo m = id >= FIRST && id <= LAST ? MAPS.get(id - FIRST) : null;
        return m != null && x >= m.cx() - m.width() / 2 && x < m.cx() + m.width() / 2 && z >= 1024 - m.length() / 2 && z < 1024 + m.length() / 2 ? m : null;
    }

    static List<MapInfo> all() {
        return MAPS;
    }

    static List<MapInfo> playable(CommunityArena p) {
        return p.world.getName().equals("community_arena_v8") ? ImportedBuilds.TEMPLATES : MAPS;
    }

    static List<MapInfo> slots(CommunityArena p) {
        return p.world.getName().equals("community_arena_v8") ? ImportedBuilds.SLOTS : MAPS;
    }

    static int available(CommunityArena p, int id, String kit) {
        var m = get(id);
        return ImportedBuilds.is(id) ? ImportedBuilds.available(p, id, kit) : m != null && m.supports(kit) && !p.occupied.contains(id) ? id : 0;
    }

    static Material icon(int id) {
        var m = get(id);
        return ImportedBuilds.is(id) ? ImportedBuilds.ICONS[m.theme()] : ICONS[m.theme()];
    }

    static int height(MapInfo m, int x, int z) {
        // Flat spawn lanes; the two sides have identical footing.
        if (Math.abs(z) < 7 || Math.abs(x) < 6) return 64;
        double wave = (Math.sin(Math.abs(x) * .055) + Math.cos(z * .048) + 2) / 4;
        return 64 + (int) (wave * (m.theme() == 2 || m.theme() == 3 ? 8 : 3));
    }

    static Location spawn(CommunityArena p, int id, boolean first) {
        if (ImportedBuilds.is(id)) return ImportedBuilds.spawn(p, id, first);
        MapInfo m = get(id);
        int x = (first ? -1 : 1) * Math.min(m.width() / 3, 55);
        return new Location(p.world, m.cx() + x + .5, 65, 1024.5, first ? -90 : 90, 0);
    }

    static boolean contains(CommunityArena p, int id, Location l) {
        MapInfo m = get(id);
        return m != null ? m.inside(l, p.world, 1) : l.getWorld().equals(p.world)
                && Math.abs(l.getX() - id * 160) < (id == 5 ? 39 : 31) && Math.abs(l.getZ()) < (id == 5 ? 39 : 31)
                && l.getY() >= 50 && l.getY() < 110;
    }

    static void build(CommunityArena p) {
        // Geometry is generated by Paper per chunk. No global construction gate or tick task.
        p.data.set(p.world.getName().equals("community_arena_v8") ? "terrain-generator-v8" : "terrain-generator-v7", true);
        p.data.set("built-battle-maps-v5", true);
    }

    static void column(CommunityArena p, MapInfo m, int x, int z) {
        ArenaLandscape.column(m, x, z, (from, to, material) -> {
            for (int y = from; y < to; y++) p.world.getBlockAt(m.cx() + x, y, 1024 + z).setType(material, false);
        });
    }
}
